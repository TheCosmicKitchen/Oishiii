"""Build src/compound-data.js: common two-kanji words made only of JLPT kanji, for Transfer Chain.

  python3 tools/make_compounds.py jmdict-eng-common.json

Input: JMdict common words from scriptin/jmdict-simplified (JMdict, EDRDG, CC BY-SA 4.0). Keeps words whose
common kanji form is exactly two JLPT N5-N2 kanji, with their first common kana reading and a short English meaning.
Drops vulgar, derogatory and X-rated senses."""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tsv = re.search(r'const KANJI_TSV = "(.*?)";\n', open(os.path.join(ROOT, "src", "kanji-data.js"), encoding="utf-8").read(), re.S).group(1)
JLPT = {r[0] for r in (l.split("\t") for l in json.loads('"' + tsv + '"').split("\n")) if r[1] != "1"}  # N5-N2; N1 words rarely help a chain
SKIP = {"vulg", "X", "derog", "obsc", "arch", "rare"}

words = json.load(open(sys.argv[1], encoding="utf-8"))["words"]
out, seen = [], set()
for w in words:
    kana = next((k["text"] for k in w["kana"] if k["common"]), None)
    sense = next((s for s in w["sense"] if not SKIP & set(s.get("misc", [])) and s["gloss"]), None)
    if not kana or not sense: continue
    meaning = re.sub(r"^\([^)]*\)\s*", "", sense["gloss"][0]["text"])
    if len(meaning) > 32: meaning = meaning[:32].rsplit(" ", 1)[0].rstrip(",;(") + "…"
    for k in w["kanji"]:
        t = k["text"]
        if k["common"] and len(t) == 2 and t[0] in JLPT and t[1] in JLPT and t[0] != t[1] and t not in seen:
            seen.add(t); out.append("\t".join([t, kana, meaning.replace("\t", " ")]))
out.sort()
js = ("// ===== Common two-kanji words for Transfer Chain =====\n"
      "// JMdict (EDRDG, CC BY-SA 4.0) via scriptin/jmdict-simplified. Generated by tools/make_compounds.py; do not edit by hand.\n"
      "const COMPOUND_TSV = " + json.dumps("\n".join(out), ensure_ascii=False) + ";\n")
open(os.path.join(ROOT, "src", "compound-data.js"), "w", encoding="utf-8").write(js)
print(f"{len(out)} words, {len(js.encode('utf-8')) // 1024} KB")
