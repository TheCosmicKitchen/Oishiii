def clean_mean(m):
    return m if m in ("Japan",) else m.lower()
def clean_kun(r):
    return r.strip("-")
order = sorted(rows, key=lambda r: (-r["n"], r["g"], r["f"], r["s"]))
used = set()
lines = []
for r in order:
    rs = [x for x in r["r"] if rad[x]["f"] != r["k"]] or r["r"]
    used.update(rs)
    ms = []
    for m in r["m"]:
        m = clean_mean(m)
        if "radical" in m and "(no" in m: continue
        if m not in ms: ms.append(m)
    ms = [m for m in ms if not m.startswith("counter")] + [m for m in ms if m.startswith("counter")]
    ms = ms or [clean_mean(r["m"][0])]
    kun = []
    for x in r["kun"]:
        x = clean_kun(x)
        if x and x not in kun: kun.append(x)
    on = [x for x in dict.fromkeys(r["on"]) if x]
    lines.append("\t".join([r["k"], str(r["n"]), str(r["s"]), ";".join(ms[:4]), ",".join(on[:3]), ",".join(kun[:4]), "".join(rs), EMOJI.get(r["k"], "")]))
rads = {k: [v["f"], rmean(k, v), v["s"]] for k, v in rad.items() if k in used}
js = ("// ===== JLPT kanji (N5–N1) with meanings, readings and radicals =====\n"
"// Kanji, meanings and readings: KANJIDIC2 (EDRDG, CC BY-SA 4.0) via davidluzgouveia/kanji-data; JLPT levels: Jonathan Waller's\n"
"// lists (tanos.co.uk, CC BY). Radicals: RADKFILE/KRADFILE (EDRDG, CC BY-SA 4.0) and radical names from Kanji alive (CC BY 4.0),\n"
"// via @johnmorrisdotca/bushu. Generated by tools/make_kanji_data.py; do not edit by hand.\n"
"const RADS = " + json.dumps(rads, ensure_ascii=False, separators=(",", ":")) + ";\n"
"const KANJI_TSV = " + json.dumps("\n".join(lines), ensure_ascii=False) + ";\n")
open(os.path.join(ROOT, "src", "kanji-data.js"), "w", encoding="utf-8").write(js)
print("kanji", len(lines), "radicals", len(rads), "bytes", len(js.encode()))
