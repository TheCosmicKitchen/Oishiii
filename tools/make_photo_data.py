"""Build src/photo-data.js: the town photos listed in tools/photos.tsv, embedded with their credits.

  python3 tools/make_photo_data.py

Each photo is a free Wikimedia Commons file, approved by hand, stored resized in assets/photos. The game shows it as a
postcard on its scene, with the author, licence and a link to the Commons page, as the licences require."""
import base64, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = [l.rstrip("\r\n").split("\t") for l in open(os.path.join(ROOT, "tools", "photos.tsv"), encoding="utf-8") if l.strip() and not l.startswith("#")]
photos = {}
for file, scene, caption, page, author, licence, licence_url in rows:
    data = base64.b64encode(open(os.path.join(ROOT, "assets", "photos", file), "rb").read()).decode()
    photos[scene] = {"src": "data:image/jpeg;base64," + data, "caption": caption, "page": page, "author": author, "licence": licence, "licenceUrl": licence_url}
js = ("// ===== Town photos: free Wikimedia Commons files shown as postcards on scenes, with their credits =====\n"
      "// Listed in tools/photos.tsv; generated by tools/make_photo_data.py; do not edit by hand.\n"
      "const SCENE_PHOTOS = " + json.dumps(photos, ensure_ascii=False) + ";\n")
open(os.path.join(ROOT, "src", "photo-data.js"), "w", encoding="utf-8").write(js)
print(f"{len(photos)} photos, {len(js) // 1024} KB")
