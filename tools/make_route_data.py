"""Build src/route-data.js: the rail route (tools/route.tsv) with station coordinates from ekidata
(via piuccio/open-data-jp-railway-stations) and a simplified outline of Japan from Global Map Japan
(GSI, via dataofjapan/land). Usage: python3 tools/make_route_data.py stations.json japan.geojson"""
import json, sys, os, math
from shapely.geometry import shape, Polygon, MultiPolygon
from shapely.ops import unary_union
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
stations = json.load(open(sys.argv[1], encoding="utf-8"))
geo = json.load(open(sys.argv[2], encoding="utf-8"))
rows = [l.rstrip("\n").split("\t") for l in open(os.path.join(ROOT, "tools", "route.tsv"), encoding="utf-8") if l.strip() and not l.startswith("#")]
want = {"kana": 6, "n5": 8, "n4": 17, "n3": 37, "n2": 37, "n1": 123}
from collections import Counter
cnt = Counter(r[0] for r in rows)
print("counts", dict(cnt), "ok" if all(cnt[k] == v for k, v in want.items()) else "MISMATCH")
idx = {}
for g in stations:
    for s in g["stations"]:
        for nm in [s["name_kanji"], *s.get("alternative_names", [])]:
            idx.setdefault(nm, []).append(s)
LAT0 = 36.0; KX = math.cos(math.radians(LAT0)) * 100; KY = 100
proj = lambda lon, lat: (round((lon - 128) * KX, 2), round((46 - lat) * KY, 2))
out, missing = [], []
for tr, st, place, kana, ro, pref, fact in rows:
    cands = [s for s in idx.get(st, []) if s["prefecture"] == pref]
    if not cands: missing.append(f"{st}({pref}) have:{sorted(set(s['prefecture'] for s in idx.get(st, [])))}"); continue
    lat = sum(s["lat"] for s in cands) / len(cands); lon = sum(s["lon"] for s in cands) / len(cands)
    spread = max(abs(s["lat"] - lat) + abs(s["lon"] - lon) for s in cands)
    if spread > 0.05: print("spread", st, round(spread, 3), [(s["lat"], s["lon"]) for s in cands][:4])
    x, y = proj(lon, lat)
    out.append({"t": tr, "st": st, "p": place, "r": kana, "ro": ro, "pref": int(pref), "f": fact, "x": x, "y": y})
print("missing", missing)
# outline: union of prefectures, drop tiny islands, simplify
polys = []
for f in geo["features"]:
    g = shape(f["geometry"]); polys.extend(g.geoms if isinstance(g, MultiPolygon) else [g])
land = unary_union(polys)
keep = [p for p in (land.geoms if isinstance(land, MultiPolygon) else [land]) if p.area > 0.02 and p.bounds[0] > 128.5 and p.bounds[1] > 30]
def path(p, tol):
    p = p.simplify(tol, preserve_topology=True)
    pts = [proj(x, y) for x, y in p.exterior.coords]
    return "M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + "Z"
d = "".join(path(p, 0.012 if p.area > 1 else 0.02) for p in sorted(keep, key=lambda p: -p.area))
prefnames = {1:"Hokkaido",2:"Aomori",3:"Iwate",4:"Miyagi",5:"Akita",6:"Yamagata",7:"Fukushima",8:"Ibaraki",9:"Tochigi",10:"Gunma",11:"Saitama",12:"Chiba",13:"Tokyo",14:"Kanagawa",15:"Niigata",16:"Toyama",17:"Ishikawa",18:"Fukui",19:"Yamanashi",20:"Nagano",21:"Gifu",22:"Shizuoka",23:"Aichi",24:"Mie",25:"Shiga",26:"Kyoto",27:"Osaka",28:"Hyogo",29:"Nara",30:"Wakayama",31:"Tottori",32:"Shimane",33:"Okayama",34:"Hiroshima",35:"Yamaguchi",36:"Tokushima",37:"Kagawa",38:"Ehime",39:"Kochi",40:"Fukuoka",41:"Saga",42:"Nagasaki",43:"Kumamoto",44:"Oita",45:"Miyazaki",46:"Kagoshima",47:"Okinawa"}
js = ("// ===== The rail route across Japan: one real station per sub-level =====\n"
"// Station coordinates: ekidata (ekidata.jp) via piuccio/open-data-jp-railway-stations. Map outline: Global Map Japan\n"
"// (Geospatial Information Authority of Japan) via dataofjapan/land. Generated by tools/make_route_data.py.\n"
"const JAPAN_PATH = " + json.dumps(d) + ";\n"
"const PREF_NAMES = " + json.dumps(prefnames) + ";\n"
"const ROUTE = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
open(os.path.join(ROOT, "src", "route-data.js"), "w", encoding="utf-8").write(js)
xs = [o["x"] for o in out]; ys = [o["y"] for o in out]
print("islands", len(keep), "path KB", len(d) // 1024, "stops", len(out), "x", min(xs), max(xs), "y", min(ys), max(ys))
